-- Gruppen: Spieler und Matches gehören genau einer Gruppe.
-- Setzt leere Tabellen player/match voraus (seit V1 gibt es keinen Weg, Spieler anzulegen). Sonst schlägt die
-- Migration beim NOT NULL absichtlich fehl, statt Daten stillschweigend zu verwerfen.

CREATE TABLE pong_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

ALTER TABLE player
    ALTER COLUMN name SET NOT NULL,
    ADD COLUMN group_id BIGINT      NOT NULL REFERENCES pong_group (id),
    -- NULL = kein Account (Account gelöscht, aus der Gruppe ausgetreten, später Platzhalter)
    ADD COLUMN user_id  BIGINT      REFERENCES app_user (id) ON DELETE SET NULL,
    ADD COLUMN role     VARCHAR(20) NOT NULL;

-- Anzeigenamen sind nur innerhalb einer Gruppe eindeutig
CREATE UNIQUE INDEX ux_player_group_name_lower ON player (group_id, lower(name));
-- Ein Account ist höchstens einmal Mitglied einer Gruppe
CREATE UNIQUE INDEX ux_player_group_user ON player (group_id, user_id) WHERE user_id IS NOT NULL;
-- "Meine Gruppen"
CREATE INDEX ix_player_user ON player (user_id);

ALTER TABLE match
    ADD COLUMN group_id BIGINT NOT NULL REFERENCES pong_group (id);

DROP INDEX ix_match_played_at;
CREATE INDEX ix_match_group_played_at ON match (group_id, played_at DESC);
