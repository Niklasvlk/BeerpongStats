-- Einladungslinks. Der Token selbst wird nie gespeichert, nur sein SHA-256-Hash (hex).
CREATE TABLE invitation (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id   BIGINT       NOT NULL REFERENCES pong_group (id),
    token_hash VARCHAR(64)  NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    max_uses   INTEGER,
    uses       INTEGER      NOT NULL DEFAULT 0,
    revoked_at TIMESTAMP(6)
);

CREATE UNIQUE INDEX ux_invitation_token_hash ON invitation (token_hash);
CREATE INDEX ix_invitation_group ON invitation (group_id);
