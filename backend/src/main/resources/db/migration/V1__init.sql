CREATE TABLE app_user (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

-- Benutzernamen sind unabhängig von der Groß-/Kleinschreibung eindeutig
CREATE UNIQUE INDEX ux_app_user_username_lower ON app_user (lower(username));

CREATE TABLE player (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255),
    wins       INTEGER          NOT NULL,
    losses     INTEGER          NOT NULL,
    win_rate   DOUBLE PRECISION NOT NULL,
    avg_cups   DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP(6)
);

CREATE TABLE match (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    winner1_id   BIGINT NOT NULL REFERENCES player (id),
    winner2_id   BIGINT REFERENCES player (id),
    loser1_id    BIGINT NOT NULL REFERENCES player (id),
    loser2_id    BIGINT REFERENCES player (id),
    winner1_cups INTEGER,
    winner2_cups INTEGER,
    loser1_cups  INTEGER,
    loser2_cups  INTEGER,
    played_at    TIMESTAMP(6)
);

CREATE INDEX ix_match_played_at ON match (played_at DESC);
